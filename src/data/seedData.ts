export function getProcedureTemplateKey(
  incidentType: IncidentType,
  floodScenario?: FloodSubScenario
): string {
  if (incidentType === 'flooding') {
    return `flooding:${floodScenario ?? 'stranded_evacuation'}`;
  }
  return incidentType;
}

